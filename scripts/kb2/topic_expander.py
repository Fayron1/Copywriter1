def generate_all() -> List[Dict]:
    """Развёртка матрицы × формулы = полный набор тем с SEO-запросами."""
    topics = []
    seen = set()

    for item in TOPIC_MATRIX:
        for formula in FORMULAS:
            title = formula["pattern"].format(
                объект=item["объект"], год=item["год"],
                объект_А=item["объект_А"], объект_Б=item["объект_Б"],
                ситуация=item["ситуация"],
                действие=item["действие"],
                объект_предложный=item["объект_предложный"],
                объект_родный=item["объект_родный"],
            )
            title = re.sub(r'\s+', ' ', title).strip()
            key = title.lower()
            if key in seen:
                continue
            seen.add(key)

            seo_query = formula["seo"].format(
                объект_кратко=item["объект_кратко"], год=item["год"],
                объект_А_кратко=item["объект_А_кратко"], объект_Б_кратко=item["объект_Б_кратко"],
                действие_кратко=item["действие_кратко"], ситуация_кратко=item["ситуация_кратко"],
            )

            topics.append({
                "title": title,
                "type": formula["type"],
                "sphere": item["sphere"],
                "formula": formula["id"],
                "seo_query": seo_query,
                "query": seo_query,
            })

            # SEO-вариация: альтернативный интент для той же темы
            alt_title = f"{title} — что проверить и с чего начать"
            alt_key = alt_title.lower()
            if alt_key not in seen:
                seen.add(alt_key)
                alt_seo = f"{seo_query} что делать"
                topics.append({
                    "title": alt_title,
                    "type": "checklist",
                    "sphere": item["sphere"],
                    "formula": formula["id"] + "_alt",
                    "seo_query": alt_seo,
                    "query": alt_seo,
                })

    return topics


if __name__ == "__main__":
    topics = generate_all()
    print(f"Сгенерировано: {len(topics)} тем")
    by_sphere = {}
    for t in topics:
        by_sphere.setdefault(t["sphere"], []).append(t)
    for sphere, ts in sorted(by_sphere.items()):
        print(f"  {sphere}: {len(ts)} тем")
    out = PROJECT / "topics_full.json"
    out.write_text(json.dumps(topics, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nСохранено: {out}")
