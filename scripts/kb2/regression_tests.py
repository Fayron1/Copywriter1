# Параметры для тестов legacy-замены
_PARAMS = {"params": [{"name": "НДС", "value": "22%", "old_value": "20%"}], "scenarios": []}


def run_tests():
    passed = 0
    failed = 0
    results = []

    for name, text, marker, checker in TESTS:
        issues = []
        try:
            if checker == "lint":
                issues = lint_legal(text)
            elif checker == "year":
                issues = lint_year_rules(text, 2026, _PARAMS)
            elif checker == "form":
                issues = lint_form_deadline(text, _PARAMS)
            elif checker == "trunc":
                issues = detect_truncation(text)
            elif checker == "legacy":
                fixed, fixes = enforce_params(text, None, article_year=2026)
                if fixes:
                    issues = [f"legacy: {f}" for f in fixes]
        except Exception as e:
            issues = [f"EXCEPTION: {e}"]

        found = any(marker.lower() in str(i).lower() for i in issues)
        status = "✓" if found else "✗"
        if found:
            passed += 1
        else:
            failed += 1
            results.append((name, text[:60], marker, [i[:60] for i in issues[:3]]))

    print(f"\n{'='*60}")
    print(f"РЕГРЕССИОННЫЙ ТЕСТ: {passed}/{passed+failed} пройдено, {failed} провалено")
    print(f"{'='*60}")

    if failed:
        print("\nПРОВАЛЕННЫЕ ТЕСТЫ:")
        for name, text, marker, issues in results:
            print(f"\n  ✗ {name}")
            print(f"    вход: {text}")
            print(f"    ожидаем: «{marker}»")
            if issues:
                for i in issues:
                    print(f"    получено: {i}")
            else:
                print(f"    получено: (пусто — правило не сработало)")

    return failed


if __name__ == "__main__":
    sys.exit(run_tests())
