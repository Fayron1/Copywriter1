_PARAMS = {"params": [{"name": "НДС", "value": "22%", "old_value": "20%"}], "scenarios": []}


def run_tests():
    passed = 0
    failed = 0
    results = []

    for name, text, marker, checker in TESTS:
        issues = []
        try:
            if checker == "lint":
                issues = lint_legal(text)
            elif checker == "year":
                issues = lint_year_rules(text, 2026, _PARAMS)
            elif checker == "form":
                issues = lint_form_deadline(text, _PARAMS)
            elif checker == "trunc":
                issues = detect_truncation(text)
            elif checker == "legacy":
                fixed, fixes = enforce_params(text, None, article_year=2026)
                if fixes:
                    issues = [f"legacy: {f}" for f in fixes]
            elif checker == "lint_neg":
                issues = lint_legal(text)
                # Негативный контроль: ни одно из новых правил не должно сработать
                new_markers = ("КЕЙС БЕЗ МАРКИРОВКИ", "ПРОГНОЗ КАК ФАКТ",
                               "СТАТЬЯ БЕЗ АКТА", "ВЕРДИКТ КАНАЛУ",
                               "ТЕРМИН БЕЗ РАСШИФРОВКИ",
                               "ПОДПИСЬ РАБОТНИКА", "МАСКИРОВКА",
                               "ОБЛАСТЬ НОРМЫ", "ВНУТРЕННИЙ КОНТРОЛЬ",
                               "КОД СПД", "КОРРЕСПОНДЕНТ",
                               "РЕПАТРИАЦИЯ", "СПД КАК",
                               "REQUIRED CONDITION", "LIMIT SCOPE",
                               "ГАРАНТИИ", "SANCTION OVERCLAIM",
                               "НЕПОДТВЕРЖДЁННАЯ", "ПУСТАЯ",
                               "GMV", "ТАРИФ БЕЗ ДАТЫ", "FBO/FBS",
                               "AI-ЖАРГОН", "КАТЕГОРИЧНОЕ", "СМЕШЕНИЕ УРОВНЕЙ",
                               "ДИАГНОСТИКА НЕ ДОКАЗАТЕЛЬСТВО", "LEGAL SCOPE",
                               "МАТРИЦА ОТВЕТСТВЕННОСТИ",
                               "ЮРИДИЧЕСКОЕ ОБЕЩАНИЕ")
                found = not any(mk.lower() in str(i).lower()
                                for i in issues for mk in new_markers)
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, text[:60], "чисто", [i[:60] for i in issues[:3]]))
                continue
            elif checker.startswith("cta_"):
                from agents.cta_renderer import render_cta, append_cta
                from agents.deliverables import build_content_package
                art = "# Т\n\nТекст статьи про НДС.\n\n## Источники\n\n- [a](http://x.ru)"
                if checker == "cta_editorial":
                    found = render_cta("налоги", "editorial") is None
                elif checker == "cta_clean":
                    cta = render_cta("налоги", "self_promo") or ""
                    found = not lint_legal(cta) and "контент-пакет" in cta.lower()
                elif checker == "cta_no_double":
                    once = append_cta(art, "налоги", "self_promo")
                    found = append_cta(once, "налоги", "self_promo") == once
                else:  # cta_default
                    found = bool(render_cta("сельское хозяйство", "self_promo"))
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, text[:60], "CTA-инвариант", []))
                continue
            elif checker == "bare_num":
                _params_bare = {"params": [
                    {"name": "Расчётная ставка НДС из цены",
                     "value": "22/122", "old_value": "20"}], "scenarios": []}
                fixed, fixes = enforce_params(text, _params_bare, article_year=2026)
                issues = [f"bare: {f}" for f in (fixes or [])]
            elif checker == "pnl":
                from agents.marketplace_calculator import calc_unit_economics, DEMO
                r = calc_unit_economics(DEMO)["result"]
                found = abs(r["net_margin_pct"] - float(marker)) < 0.1
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, "DEMO P&L", marker, [str(r)]))
                continue
            elif checker == "proc_calc":
                from agents.procurement_calculator import calc_security, DEMO
                r = calc_security(DEMO)["антидемпинг"]
                found = (abs(r["итоговое_ОИК"] - float(marker)) < 1
                         and r["снижение_%"] > 25 and r["НМЦК_больше_15_млн"])
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, "DEMO 44-ФЗ", marker, [str(r)]))
                continue
            elif checker == "proc_pen":
                from agents.procurement_calculator import (calc_penalties,
                                                           PenaltyInput, DEMO_PEN,
                                                           _tier_pct, SME_FINE_TIERS)
                r = calc_penalties(DEMO_PEN)["итог"]
                found = (abs(r["итого_поставщик"] - float(marker)) < 1
                         and abs(r["пени_поставщика"] - 52250.0) < 1
                         and r["штраф_заказчика"] == 5000
                         and _tier_pct(2_000_000, SME_FINE_TIERS) == 3.0)
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, "DEMO неустойка", marker, [str(r)]))
                continue
            elif checker == "proc_event":
                from agents.regulatory_events import check_event_domain
                res = check_event_domain(text, "маркетинг")
                issues = res
            elif checker == "autofix":
                from agents.autofix_gate import autofix
                if marker == "unit_fix":
                    import agents.norm_params as _np
                    _enforce = _np.enforce_params
                    prm = {"params": [{"name": "ставка НДС", "value": "22%",
                                       "old_value": "20%"},
                                      {"name": "порог", "value": "20 млн",
                                       "old_value": "60 млн"}],
                           "scenarios": []}
                    fixed, _ = _enforce(
                        "НДС по ставке 20% с вычетами, порог 60 млн.",
                        prm, article_year=2026)
                    found = ("22%" in fixed and "20 млн" in fixed
                             and "ставке 22 " not in fixed)
                elif marker == "passport_keys":
                    from agents.deliverables import build_source_passport
                    pp = build_source_passport(
                        [{"claim_type": "legal_rule", "text": "Срок жалобы 5 дней",
                          "risk": "high", "status": "supported"}],
                        [], "Жалоба в ФАС по 44-ФЗ")
                    found = len(pp["high_risk_claims"]) == 1
                elif marker == "autofix2":
                    t = ("## Практика применения антидемпинговых мер (ст. 37) "
                         "и расчёт обеспечений\nЗаказчик вправе отклонить "
                         "такую гарантию. Деньги могут остаться "
                         "заблокированными.")
                    fixed, log = autofix(t)
                    found = ("СМП и СОНКО" in fixed
                             and "заявка участника может быть отклонена" in fixed
                             and "последствия, предусмотренные" in fixed
                             and len(log) == 3)
                elif marker == "autofix30_neg":
                    t = ("Запрос документов — не позднее 30 дней с даты "
                         "получения, без связи с жалобами по 44-ФЗ.")
                    fixed, log = autofix(t)
                    found = (fixed == t and not log)
                elif marker == "autofix30":
                    t = ("Жалоба на итоговый протокол по 44-ФЗ подаётся не "
                         "позднее 30 календарных дней со дня размещения "
                         "протокола. Разбираем требования к заявителю, "
                         "причины возврата и порядок рассмотрения. Отдельно: "
                         "обращение гражданина, не являющегося участником, "
                         "по 59-ФЗ рассматривается 30 дней.")
                    fixed, _ = autofix(t)
                    found = ("не позднее пяти дней" in fixed
                             and "30 календарных" not in fixed
                             and "рассматривается 30 дней" in fixed)
                else:
                    t = ("Срок по имеющимся данным обычно опирается на "
                         "положения ч. 2 ст. 105 Закона № 44-ФЗ.")
                    fixed, _ = autofix(t)
                    found = ("по имеющимся данным" not in fixed)
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, "autofix", marker, [fixed[:120]]))
                continue
            elif checker in ("rag_boost", "rag_boost_neg"):
                from agents.rag import apply_direction_boost
                chunks = [
                    {"score": 0.8754, "source_file": "legislation/НК_РФ_ред_2026-08-04.pdf"},
                    {"score": 0.8753, "source_file": "legislation/КоАП_РФ_ред_2026.pdf"},
                    {"score": 0.8725, "source_file": "legislation/44-ФЗ_снимок_пороги.txt"},
                ]
                if checker == "rag_boost":
                    out = apply_direction_boost(chunks, "закупки")
                    found = (out[0]["source_file"].startswith("legislation/44-ФЗ_снимок")
                             and abs(out[0]["score"] - 0.8725 * 1.04) < 1e-9
                             and len(out) == 3)
                else:
                    out = apply_direction_boost(chunks, "")
                    found = (out[0]["source_file"].startswith("legislation/НК")
                             and out[0]["score"] == 0.8754)
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, "boost", marker, [str(out[:2])]))
                continue
            elif checker == "normref":
                from agents.contradiction_checker import check_norm_references
                issues = check_norm_references(text, "принят закон № 144-ФЗ от 25.05.2026")
            elif checker == "cta_route":
                from agents.cta_renderer import render_cta
                cta = render_cta("закупки", "self_promo", topic_hint=text) or ""
                found = marker in cta
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, text[:60], marker, [cta[:80]]))
                continue
            elif checker in ("math", "math_neg", "contra", "detex",
                             "event", "event_neg", "entities", "entities_neg",
                             "entities2", "htmlv", "tier"):
                if checker == "math":
                    from agents.math_validator import validate_math
                    issues = validate_math(text)
                elif checker == "math_neg":
                    from agents.math_validator import validate_math
                    found = not validate_math(text)
                    status = "✓" if found else "✗"
                    if found:
                        passed += 1
                    else:
                        failed += 1
                        results.append((name, text[:60], "математика чиста", []))
                    continue
                elif checker == "contra":
                    from agents.contradiction_checker import check_h1_support
                    issues = check_h1_support(text)
                elif checker in ("event", "event_neg"):
                    from agents.regulatory_events import check_event_domain
                    res = check_event_domain(text, "трудовое")
                    if checker == "event":
                        issues = res
                    else:
                        found = not res
                        status = "✓" if found else "✗"
                        if found:
                            passed += 1
                        else:
                            failed += 1
                            results.append((name, text[:60], "чисто", res[:2]))
                        continue
                elif checker in ("entities", "entities_neg", "entities2"):
                    from agents.html_and_entities import check_required_entities
                    direction = {"entities": "защита данных",
                                 "entities_neg": "защита данных",
                                 "entities2": "налоги"}[checker]
                    res = check_required_entities(text, direction)
                    if checker.endswith("_neg"):
                        found = not res
                        status = "✓" if found else "✗"
                        if found:
                            passed += 1
                        else:
                            failed += 1
                            results.append((name, text[:60], "чисто", res[:2]))
                        continue
                    issues = res
                elif checker == "htmlv":
                    from agents.html_and_entities import validate_html
                    issues = validate_html(text)
                elif checker == "detex":
                    from agents.draft_claim_extractor import extract_claims_deterministic
                    claims = extract_claims_deterministic(text)
                    issues = [f"detex:{c['type']}:{c['value']}" for c in claims]
                else:  # tier
                    from agents.deliverables import TIER_BY_DIRECTION
                    found = TIER_BY_DIRECTION.get(text) == marker
                    status = "✓" if found else "✗"
                    if found:
                        passed += 1
                    else:
                        failed += 1
                        results.append((name, text, marker, []))
                    continue
            elif checker == "bare_year":
                _params_bare = {"params": [
                    {"name": "Расчётная ставка НДС из цены",
                     "value": "22/122", "old_value": "20"}], "scenarios": []}
                fixed, fixes = enforce_params(text, _params_bare, article_year=2026)
                found = "2026" in fixed and "22/12226" not in fixed
                status = "✓" if found else "✗"
                if found:
                    passed += 1
                else:
                    failed += 1
                    results.append((name, fixed[:80], "год не тронут",
                                    [f"bare: {f}" for f in (fixes or [])[:3]]))
                continue
        except Exception as e:
            issues = [f"EXCEPTION: {e}"]

        found = any(marker.lower() in str(i).lower() for i in issues)
        status = "✓" if found else "✗"
        if found:
            passed += 1
        else:
            failed += 1
            results.append((name, text[:60], marker, [i[:60] for i in issues[:3]]))

    print(f"\n{'='*60}")
    print(f"РЕГРЕССИОННЫЙ ТЕСТ: {passed}/{passed+failed} пройдено, {failed} провалено")
    print(f"{'='*60}")

    if failed:
        print("\nПРОВАЛЕННЫЕ ТЕСТЫ:")
        for name, text, marker, issues in results:
            print(f"\n  ✗ {name}")
            print(f"    вход: {text}")
            print(f"    ожидаем: «{marker}»")
            if issues:
                for i in issues:
                    print(f"    получено: {i}")
            else:
                print(f"    получено: (пусто — правило не сработало)")

    return failed


if __name__ == "__main__":
    sys.exit(run_tests())
