def _lint_cta(text: str) -> bool:
    """True, если в CTA нет запрещённых коммерческих утверждений."""
    low = text.lower()
    return not any(bad in low for bad in AUTHOR_PROFILE["prohibited_claims"])


def render_cta(direction: str, mode: str = "self_promo",
               profile: Optional[Dict] = None,
               topic_hint: str = "") -> Optional[str]:
    """Собрать CTA-блок. Возвращает markdown или None (режим editorial).

    mode:
      editorial  — None (нейтральный финал, коммерции нет)
      self_promo — блок услуг автора
    topic_hint — тема статьи для суб-маршрутизации внутри домена
    """
    if mode != "self_promo":
        return None

    prof = profile or AUTHOR_PROFILE
    # Суб-маршрутизация по теме: внутри домена «закупки» валютный контроль/ВЭД
    # и госзакупки — разные аудитории (ревью 20: 44-ФЗ CTA в статье про платёж)
    import re as _re
    key = (direction or "").strip().lower()
    if key == "закупки" and _re.search(
            r"валют|115-ФЗ|ВЭД|внешнеэконом|экспорт|импорт|платеж\w*\s+нерезидент|"
            r"заблокировал\s+(?:счёт|валютн)", topic_hint or "", _re.I):
        key = "вэд"
    # суб-маршрут: маркетплейсы/селлеры внутри «маркетинга»
    if key == "маркетинг" and _re.search(
            r"маркетплейс|селлер|WB|Ozon|Озон|Wildberries|вайлдберриз|FBO|FBS|"
            r"юнит-экономик", topic_hint or "", _re.I):
        key = "маркетплейсы"
    tpl = CTA_TEMPLATES.get(key, _DEFAULT_TEMPLATE)

    # CTA_DOMAIN_MISMATCH: сущности шаблона не пересекаются с темой — фолбэк
    _TPL_ENTITIES = {
        "закупки": ["закуп", "тендер", "госконтракт", "44"],
        "вэд": ["валют", "115", "вэд", "платн", "банк", "контракт", "импорт", "экспорт"],
        "налоги": ["налог", "усн", "ндс", "ндфл", "взнос", "патент"],
        "трудовое": ["трудов", "кадр", "сотрудник", "гпх", "кэдо"],
        "защита данных": ["152", "персональн", "данн", "утечк", "ркомнадзор"],
        "маркетинг": ["маркетинг", "реклам", "seo", "лид", "воронк"],
        "маркетплейсы": ["маркетплейс", "селлер", "wb", "ozon", "озон",
                         "wildberries", "вайлдберриз", "fbo", "fbs", "юнит"],
    }
    ents = _TPL_ENTITIES.get(key)
    if ents and topic_hint and not any(
            _re.search(e, topic_hint, _re.I) for e in ents):
        tpl = CTA_TEMPLATES["generic"]  # безопасный универсальный шаблон

    block = (
        "---\n\n"
        f"{tpl['lead']}\n\n"
        f"{tpl['offer']}\n\n"
        f"**{tpl['cta']}**"
    )
    if not _lint_cta(block):
        # Шаблон скомпрометирован — не показываем ничего, кроме лид-абзаца
        block = f"---\n\n{tpl['lead']}"
    return block


def append_cta(article: str, direction: str, mode: str = "self_promo",
               profile: Optional[Dict] = None, topic_hint: str = "") -> str:
    """Вклеить CTA в самый конец статьи (после «Источников»).

    Футер после источников — стандартное место: не вмешивается в тело
    и не ломает TOC, сгенерированный из H2.
    """
    cta = render_cta(direction, mode, profile, topic_hint=topic_hint)
    if not cta or not article:
        return article
    # Защита от двойной вставки при повторном прогоне
    anchor = cta[:60]
    if anchor and anchor in article:
        return article
    return article.rstrip() + "\n\n" + cta + "\n"
