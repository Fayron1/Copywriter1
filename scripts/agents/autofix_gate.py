def autofix(text: str) -> Tuple[str, List[str]]:
    """Применить детерминированные правки. Возвращает (текст, список отчёта)."""
    log: List[str] = []
    for entry in AUTOFIXES:
        pat, repl, guard, desc = entry[0], entry[1], entry[2], entry[3]
        require = entry[4] if len(entry) > 4 else None
        out_parts = []
        pos = 0
        for m in pat.finditer(text):
            window = text[max(0, m.start() - 200):m.end() + 200]
            if require and not require.search(window):
                out_parts.append(text[pos:m.start()])
                out_parts.append(m.group(0))
                pos = m.end()
                continue
            if guard and guard.search(window):
                out_parts.append(text[pos:m.start()])
                out_parts.append(m.group(0))
                pos = m.end()
                continue
            out_parts.append(text[pos:m.start()])
            out_parts.append(m.expand(repl) if "\\" in repl or m.groups() else repl)
            pos = m.end()
            log.append(f"автофикс: {desc}")
        out_parts.append(text[pos:])
        text = "".join(out_parts)
    return text, log


# ── Слой 2: гейт публикации ────────────────────────────────────
def gate(text: str, markers_path: str = None) -> List[str]:
    """Красные замечания после автофикса = публикация запрещена.

    PATCH_NOT_APPLIED (рекомендация агента, 2026-10-02): рядом со статьёй
    может лежать gate_markers.json — required_absent / required_present.
    Несоответствие = блокировка: патч не применился, в бот уйдёт старая
    версия."""
    from agents.norm_params import lint_legal
    from agents.math_validator import validate_math
    issues = lint_legal(text) + validate_math(text)
    reds = [i for i in issues if str(i).startswith("🔴")]
    if markers_path:
        import json, os
        if os.path.exists(markers_path):
            try:
                mk = json.load(open(markers_path, encoding="utf-8"))
            except Exception:
                mk = {}
            for bad in mk.get("required_absent", []):
                if bad in text:
                    reds.append(f"🔴 PATCH_NOT_APPLIED: в тексте остался "
                                f"запрещённый фрагмент «{bad}»")
            for good in mk.get("required_present", []):
                if good not in text:
                    reds.append(f"🔴 PATCH_NOT_APPLIED: в тексте НЕТ "
                                f"обязательного фрагмента «{good}»")
    return reds


def fix_dir(art_dir: str) -> Tuple[int, List[str]]:
    """Автофикс ВСЕХ текстовых файлов пакета.

    Кейс 26 (2026-10-02): article.md вылечен, а article.html в архиве
    остался старым (генерился до фикса) — ревьюер читал HTML и видел
    исходные ошибки. Лечим md + html + txt единым прогоном.
    """
    total = 0
    all_log: List[str] = []
    root = Path(art_dir)
    for f in sorted(root.iterdir()):
        if not f.is_file() or f.suffix.lower() not in (".md", ".txt", ".html"):
            continue
        text = f.read_text(encoding="utf-8")
        fixed, log = autofix(text)
        if fixed != text:
            f.write_text(fixed, encoding="utf-8")
            all_log.append(f"[{f.name}] " + "; ".join(log))
            total += len(log)
    return total, all_log


def run_file(path: str) -> int:
    text = open(path, encoding="utf-8").read()
    fixed, log = autofix(text)
    for line in log:
        print("  ✓", line)
    reds = gate(fixed, os.path.join(os.path.dirname(path), "gate_markers.json"))
    if fixed != text:
        open(path, "w", encoding="utf-8").write(fixed)
        print(f"Файл обновлён: {len(log)} автофиксов")
    else:
        print("Автофиксы не потребовались")
    if reds:
        print(f"🔴 ГЕЙТ: {len(reds)} красных замечаний — отправка в бот ЗАПРЕЩЕНА")
        for r in reds[:6]:
            print("  •", str(r)[:140])
        return 1
    print("✅ ГЕЙТ ПРОЙДЕН: красных замечаний нет")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Использование: autofix_gate.py <article.md>")
        sys.exit(2)
    sys.exit(run_file(sys.argv[1]))
