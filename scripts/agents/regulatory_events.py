def check_event_domain(text: str, direction: str) -> List[str]:
    """Если статья датирует событие и утверждает его применимость к своему
    домену, а событие принадлежит другому домену — 🟡 EVENT_DOMAIN_MISMATCH."""
    issues = []
    if not text or not direction:
        return issues
    for ev in REGULATORY_EVENTS:
        date_hit = re.search(ev["date_rx"], text)
        if not date_hit:
            continue
        # сущности события упомянуты?
        entity_hits = sum(1 for e in ev["entities"] if re.search(e, text, re.I))
        if entity_hits == 0:
            continue
        # домен события ≠ домен статьи, при этом есть маркер обязательности
        dom = ev["domain"]
        same = (dom == direction) or (
            dom == "платформенная экономика" and direction in ("трудовое", "закупки"))
        if same:
            continue
        if re.search(r"обязател|дедлайн|требование\s+для\s+всех|всеобщ", text, re.I):
            issues.append(
                f"🟡 EVENT DOMAIN MISMATCH: статья (домен «{direction}») привязывает "
                f"событие «{ev['date']}» ({dom}: {ev['note']}) к своему домену как "
                f"обязательное. Проверьте, тот ли это дедлайн — у событий одной "
                f"даты разные адресаты")
    return issues
